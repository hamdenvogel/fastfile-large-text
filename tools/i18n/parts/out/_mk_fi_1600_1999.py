# verify tokens / pipes / newlines
import re
FMT = re.compile(r'%[%\-0-9.*]*[sduxf]|%%')
for i in range(1600, 2000):
    s, t = src[i], T[i]
    if s[:len(s) - len(s.lstrip())] != t[:len(t) - len(t.lstrip())]:
        raise SystemExit(f"leading ws {i}")
    if s[len(s.rstrip()):] != t[len(t.rstrip()):]:
        raise SystemExit(f"trailing ws {i}")
    if s.count("|") != t.count("|"):
        raise SystemExit(f"pipe count {i}: {s.count('|')} vs {t.count('|')}")
    if s.count("\r\n") != t.count("\r\n"):
        raise SystemExit(f"crlf count {i}")
    if s.count("\n") != t.count("\n"):
        raise SystemExit(f"lf count {i}")
    sf, tf = FMT.findall(s), FMT.findall(t)
    if sf != tf:
        raise SystemExit(f"format tokens {i}: {sf} vs {tf}")
    if not t.strip() and s.strip():
        raise SystemExit(f"empty {i}")


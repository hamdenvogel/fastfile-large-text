def fmt_tokens(s: str):
    return FMT.findall(s)


def leading_ws(s: str):
    i = 0
    while i < len(s) and s[i] in " \t":
        i += 1
    return s[:i]


def trailing_ws(s: str):
    i = len(s)
    while i > 0 and s[i - 1] in " \t":
        i -= 1
    return s[i:]


def linebreaks(s: str):
    return re.findall(r"\r\n|\n|\r", s)


